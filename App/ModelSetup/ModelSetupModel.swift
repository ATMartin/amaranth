import Foundation
import Observation
import Domain
import Models

/// Drives first-run model installation. Installation is a separate, explicit step from permissions; the app stays usable
/// for recording ("record-only") whatever state this is in.
@MainActor @Observable
final class ModelSetupModel {
    enum Status: Equatable {
        case checking
        case recordOnly(reason: String)
        case installing(InstallProgress)
        case ready(packID: String, version: String)
        case failed(String)
    }

    private(set) var status: Status = .checking
    private(set) var pack: ModelPack?
    private(set) var availableBytes: Int64?
    private var task: Task<Void, Never>?
    private var cancellation: CancellationToken?
    let store: ModelPackStore
    /// Called after a pack installs and verifies (the app asks the worker to warm the models up).
    var onInstalled: (() -> Void)?

    init(store: ModelPackStore = ModelPackStore(root: ModelPackStore.defaultRoot())) {
        self.store = store
        pack = Self.bundledPack()
        refresh()
    }

    /// The pack definition shipped with the app (generated by `amaranth-models build-pack` from the T02 decision).
    static func bundledPack() -> ModelPack? {
        guard let url = Bundle.main.url(forResource: "default-model-pack", withExtension: "json"),
              let data = try? Data(contentsOf: url) else { return nil }
        return try? ContractCoding.decode(ModelPack.self, from: data)
    }

    /// Whether the installed pack verifies (used by live text before sending work to the worker).
    nonisolated static func isReady() -> Bool {
        if case .ready = LocalModelRegistry(store: ModelPackStore(root: ModelPackStore.defaultRoot())).state() { return true }
        return false
    }

    var downloadBytes: Int64 { pack?.manifests.reduce(0) { $0 + $1.totalBytes } ?? 0 }
    var requiredFreeBytes: Int64 { pack.map { ModelInstaller(store: store).requiredBytes(for: $0) } ?? 0 }

    func refresh() {
        availableBytes = ModelPackStore.availableBytes(at: store.root)
        switch LocalModelRegistry(store: store).state() {
        case .ready(let id, let v): status = .ready(packID: id, version: v)
        case .notInstalled: status = .recordOnly(reason: "Models are not installed. Recording works; transcripts and notes need the model pack.")
        case .corrupt(let id, let path):
            status = .recordOnly(reason: "Model file \(id)/\(path) is damaged. Recording works; reinstall or import the pack to restore transcription. Nothing was downloaded automatically.")
        }
    }

    func install(fromDirectory dir: URL? = nil) {
        guard let pack, task == nil else { return }
        let token = CancellationToken()
        cancellation = token
        let source: any ModelSource = dir.map { DirectoryModelSource(root: $0) } ?? HTTPModelSource()
        let installer = ModelInstaller(store: store)
        status = .installing(InstallProgress(phase: .checkingSpace, bytesDone: 0, bytesTotal: downloadBytes))
        task = Task {
            do {
                try await installer.install(pack, from: source, cancellation: token) { p in
                    Task { @MainActor in self.status = .installing(p) }
                }
                refresh()
                if case .ready = status { onInstalled?() }
            } catch is CancellationError {
                status = .recordOnly(reason: "Installation cancelled. Downloaded parts are kept and the next install resumes.")
            } catch ModelInstallError.insufficientSpace(let need, let have) {
                status = .failed("Not enough free space: need \(Self.gb(need)), have \(Self.gb(have)).")
            } catch {
                status = .failed("Installation failed: \(error). No partial model was activated.")
            }
            task = nil
        }
    }

    func cancel() { cancellation?.cancel() }

    static func gb(_ b: Int64) -> String { String(format: "%.2f GB", Double(b) / 1e9) }
}
